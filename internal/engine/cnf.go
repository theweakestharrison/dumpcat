package engine

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"dumpcat/internal/store"
)

// cnfSafe reports whether a value can be written unquoted into an option file.
func cnfSafe(v string) bool {
	if v == "" {
		return true
	}
	if strings.TrimSpace(v) != v {
		return false
	}
	return !strings.ContainsAny(v, "#;'\"\\\n\r\t ")
}

// cnfQuoted renders a value for the MySQL option-file parser.
func cnfQuoted(v string) string {
	if cnfSafe(v) {
		return v
	}
	return `"` + strings.ReplaceAll(v, `\`, `\\`) + `"`
}

// glibEscaped renders a value for GKeyFile-based parsers (newer mydumper).
func glibEscaped(v string) string {
	r := strings.NewReplacer(`\`, `\\`, "\n", `\n`, "\t", `\t`, "\r", `\r`)
	v = r.Replace(v)
	if strings.HasPrefix(v, " ") {
		v = `\s` + v[1:]
	}
	return v
}

type CnfOptions struct {
	// Groups receiving connection options parsed by the MySQL option parser.
	Groups []string
	// GlibGroups receive connection options escaped for GKeyFile (mydumper).
	GlibGroups []string
	// TLS options are only written to [client]; MariaDBClient selects syntax.
	TLS           bool
	MariaDBClient bool
}

// WriteCnf writes a private option file with connection credentials so that
// passwords never appear on a command line. It returns the file path and
// extra environment variables (MYSQL_PWD fallback).
func WriteCnf(dir string, s *store.Server, o CnfOptions) (string, []string, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", nil, err
	}
	host, port, socket, err := s.Addr() // direct, or the local end of an agent tunnel
	if err != nil {
		return "", nil, err
	}
	conn := func(glib bool) []string {
		var lines []string
		if s.Username != "" {
			lines = append(lines, "user="+cnfQuoted(s.Username))
		}
		if s.Password != "" {
			if glib {
				lines = append(lines, "password="+glibEscaped(s.Password))
			} else {
				// Values with newlines, or with both '"' and '#', cannot be
				// represented reliably; MYSQL_PWD is used as fallback then.
				risky := strings.ContainsAny(s.Password, "\n\r") || (strings.Contains(s.Password, `"`) && strings.Contains(s.Password, "#"))
				if !risky {
					lines = append(lines, "password="+cnfQuoted(s.Password))
				}
			}
		}
		if socket != "" {
			lines = append(lines, "socket="+cnfQuoted(socket))
			if host == "localhost" {
				lines = append(lines, "host=localhost")
			}
		} else {
			lines = append(lines, "host="+cnfQuoted(host))
			lines = append(lines, "port="+strconv.Itoa(port))
		}
		return lines
	}
	var sb strings.Builder
	sb.WriteString("# generated by DumpCat, removed after use\n")
	for _, g := range o.Groups {
		fmt.Fprintf(&sb, "[%s]\n", g)
		for _, l := range conn(false) {
			sb.WriteString(l + "\n")
		}
		if g == "client" && o.TLS {
			for _, l := range tlsLines(dir, s, o.MariaDBClient) {
				sb.WriteString(l + "\n")
			}
		}
	}
	for _, g := range o.GlibGroups {
		fmt.Fprintf(&sb, "[%s]\n", g)
		for _, l := range conn(true) {
			sb.WriteString(l + "\n")
		}
	}
	f, err := os.CreateTemp(dir, "conn-*.cnf")
	if err != nil {
		return "", nil, err
	}
	if _, err := f.WriteString(sb.String()); err != nil {
		f.Close()
		return "", nil, err
	}
	f.Close()
	var env []string
	if s.Password != "" {
		env = append(env, "MYSQL_PWD="+s.Password)
	}
	return f.Name(), env, nil
}

func tlsLines(dir string, s *store.Server, maria bool) []string {
	caFile := ""
	if strings.TrimSpace(s.CACert) != "" {
		caFile = filepath.Join(dir, "ca.pem")
		_ = os.WriteFile(caFile, []byte(s.CACert), 0o600)
	}
	var l []string
	if maria {
		switch s.TLSMode {
		case "disabled":
			l = append(l, "skip-ssl")
		case "required":
			l = append(l, "ssl", "skip-ssl-verify-server-cert")
		case "verify":
			l = append(l, "ssl", "ssl-verify-server-cert")
		default:
			// MariaDB >= 11.4 clients verify certificates by default, which
			// breaks against servers with self-signed certificates.
			l = append(l, "skip-ssl-verify-server-cert")
		}
	} else {
		switch s.TLSMode {
		case "disabled":
			l = append(l, "ssl-mode=DISABLED")
		case "required":
			l = append(l, "ssl-mode=REQUIRED")
		case "verify":
			l = append(l, "ssl-mode=VERIFY_IDENTITY")
		}
	}
	if caFile != "" && s.TLSMode == "verify" {
		l = append(l, "ssl-ca="+cnfQuoted(caFile))
	}
	return l
}

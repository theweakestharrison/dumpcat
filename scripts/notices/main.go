// Command notices writes THIRD_PARTY_NOTICES.md: the name, version, license and full license
// text of every Go module compiled into the release binaries, plus the Go standard library.
//
//	go run ./scripts/notices          # regenerate THIRD_PARTY_NOTICES.md (after changing go.mod)
//	go run ./scripts/notices -check   # fail if the file is out of date (build.sh / build.ps1 run this)
//
// The license texts are read from the module cache (go mod download fills it). A license file it
// cannot identify is an error, so a new dependency is always looked at before it ships.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// platforms are the targets build.sh / build.ps1 release.
var platforms = []string{"linux/amd64", "linux/arm64", "windows/amd64"}

const mainPkg = "./cmd/dumpcat"

// licenseFile matches LICENSE, LICENSE.txt, LICENSE-3RD-PARTY.md, COPYING, NOTICE, PATENTS, ...
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|copyright|notice|patents|unlicense)([-._][^/\\]*)?$`)

type module struct {
	Path, Version, Dir string
	pkgDirs            map[string]bool // directories of the compiled packages
	platforms          map[string]bool
}

type licenseText struct {
	Name  string // path relative to the module root, slash-separated
	Kinds []string
	Text  string
}

func main() {
	out := flag.String("o", "THIRD_PARTY_NOTICES.md", "output file")
	check := flag.Bool("check", false, "only check that the output file is up to date")
	flag.Parse()

	doc, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		cur, err := os.ReadFile(*out)
		if err == nil && bytes.Equal(bytes.ReplaceAll(cur, []byte("\r\n"), []byte("\n")), doc) {
			return
		}
		fmt.Fprintf(os.Stderr, "notices: %s is out of date with go.mod; run: go run ./scripts/notices\n", *out)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, doc, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	fmt.Println("wrote", *out)
}

func generate() ([]byte, error) {
	mods, err := compiledModules()
	if err != nil {
		return nil, err
	}
	goroot, err := goOutput(nil, "env", "GOROOT")
	if err != nil {
		return nil, err
	}
	goVersion, err := goOutput(nil, "list", "-m", "-f", "{{.GoVersion}}")
	if err != nil {
		return nil, err
	}
	std, err := readLicenses(goroot, nil)
	if err != nil {
		return nil, fmt.Errorf("Go standard library: %w", err)
	}

	var b strings.Builder
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("DumpCat is licensed under the Apache License 2.0 (see [LICENSE](LICENSE) and [NOTICE](NOTICE)).\n")
	b.WriteString("The DumpCat binaries also contain the Go standard library and the Go modules listed below. Each is\n")
	b.WriteString("distributed under its own license, reproduced in full in this file. A module's combined notice file\n")
	b.WriteString("(such as LICENSE-3RD-PARTY.md) is reproduced as shipped; it may also list parts of that module that\n")
	b.WriteString("DumpCat does not compile in.\n\n")
	b.WriteString("This file is generated by `go run ./scripts/notices` from go.mod and the Go module cache. Do not edit it by hand.\n\n")

	b.WriteString("| Module | Version | License | Binaries |\n|---|---|---|---|\n")
	fmt.Fprintf(&b, "| Go standard library and runtime | go %s or later | %s | all |\n", goVersion, summary(std))
	lics := make([][]licenseText, len(mods))
	for i, m := range mods {
		if lics[i], err = readLicenses(m.Dir, m.pkgDirs); err != nil {
			return nil, fmt.Errorf("%s %s: %w", m.Path, m.Version, err)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", m.Path, m.Version, summary(lics[i]), m.binaries())
	}

	if mpl := mplModules(mods, lics); len(mpl) > 0 {
		b.WriteString("\n## Source code of MPL-2.0 modules\n\n")
		b.WriteString("DumpCat uses the modules licensed under the Mozilla Public License 2.0 unmodified. Their source code\n")
		b.WriteString("is available from upstream and from the Go module proxy:\n\n")
		for _, m := range mpl {
			fmt.Fprintf(&b, "- %s %s: %s, https://proxy.golang.org/%s/@v/%s.zip\n", m.Path, m.Version, upstream(m), escapePath(m.Path), escapePath(m.Version))
		}
	}

	b.WriteString("\n## Go standard library and runtime\n\n")
	fmt.Fprintf(&b, "- Version: the Go toolchain that built the binaries (go.mod requires go %s or later)\n", goVersion)
	b.WriteString("- Source: https://go.dev/dl/ (this includes the golang.org/x packages vendored into the standard library)\n")
	writeTexts(&b, std)
	for i, m := range mods {
		fmt.Fprintf(&b, "\n## %s %s\n\n", m.Path, m.Version)
		fmt.Fprintf(&b, "- License: %s\n", summary(lics[i]))
		fmt.Fprintf(&b, "- Source: %s\n", upstream(m))
		if bins := m.binaries(); bins != "all" {
			fmt.Fprintf(&b, "- Included in the %s binaries only\n", bins)
		}
		writeTexts(&b, lics[i])
	}
	return []byte(b.String()), nil
}

// compiledModules returns the modules of every package linked into mainPkg on any release platform.
func compiledModules() ([]*module, error) {
	byPath := map[string]*module{}
	for _, p := range platforms {
		goos, goarch, _ := strings.Cut(p, "/")
		env := []string{"GOOS=" + goos, "GOARCH=" + goarch, "CGO_ENABLED=0"}
		out, err := goOutput(env, "list", "-deps", "-json=ImportPath,Dir,Standard,Module", mainPkg)
		if err != nil {
			return nil, err
		}
		dec := json.NewDecoder(strings.NewReader(out))
		for {
			var pkg struct {
				ImportPath, Dir string
				Standard        bool
				Module          *struct {
					Path, Version, Dir string
					Main               bool
					Replace            *struct{ Path, Version, Dir string }
				}
			}
			if err := dec.Decode(&pkg); errors.Is(err, io.EOF) {
				break
			} else if err != nil {
				return nil, fmt.Errorf("go list: %w", err)
			}
			if pkg.Standard || pkg.Module == nil || pkg.Module.Main {
				continue
			}
			mod := *pkg.Module
			if r := mod.Replace; r != nil {
				mod.Version, mod.Dir = r.Version, r.Dir
				if r.Version != "" {
					mod.Path = r.Path
				}
			}
			if mod.Dir == "" {
				return nil, fmt.Errorf("%s %s is not in the module cache; run: go mod download", mod.Path, mod.Version)
			}
			m := byPath[mod.Path]
			if m == nil {
				m = &module{Path: mod.Path, Version: mod.Version, Dir: mod.Dir, pkgDirs: map[string]bool{}, platforms: map[string]bool{}}
				byPath[mod.Path] = m
			}
			m.pkgDirs[pkg.Dir] = true
			m.platforms[p] = true
		}
	}
	mods := make([]*module, 0, len(byPath))
	for _, m := range byPath {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

// readLicenses returns the license files at the module root and in every directory between the
// root and a compiled package (a vendored sub-package may carry its own license).
func readLicenses(root string, pkgDirs map[string]bool) ([]licenseText, error) {
	dirs := map[string]bool{".": true}
	for d := range pkgDirs {
		rel, err := filepath.Rel(root, d)
		if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			continue
		}
		for rel != "." {
			dirs[filepath.ToSlash(rel)] = true
			rel = filepath.Dir(rel)
		}
	}
	var names []string
	for d := range dirs {
		entries, err := os.ReadDir(filepath.Join(root, filepath.FromSlash(d)))
		if err != nil {
			return nil, err
		}
		for _, e := range entries {
			// LICENSE-LOGO and the like cover a project logo, which is not compiled in
			if e.Type().IsRegular() && licenseFile.MatchString(e.Name()) && !strings.Contains(strings.ToLower(e.Name()), "logo") {
				names = append(names, strings.TrimPrefix(d+"/"+e.Name(), "./"))
			}
		}
	}
	if len(names) == 0 {
		return nil, errors.New("no license file found")
	}
	// the module root first, then sub-directories
	sort.Slice(names, func(i, j int) bool {
		di, dj := strings.Count(names[i], "/"), strings.Count(names[j], "/")
		if di != dj {
			return di < dj
		}
		return names[i] < names[j]
	})
	var lics []licenseText
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		text := strings.TrimSpace(strings.ReplaceAll(string(data), "\r\n", "\n"))
		kinds := classify(name, text)
		if len(kinds) == 0 {
			return nil, fmt.Errorf("cannot identify the license in %s; read it and extend classify() in scripts/notices", name)
		}
		lics = append(lics, licenseText{Name: name, Kinds: kinds, Text: text})
	}
	return lics, nil
}

var spaces = regexp.MustCompile(`\s+`)

// classify names the licenses whose wording appears in a license file.
func classify(name, text string) []string {
	t := spaces.ReplaceAllString(strings.ToLower(text), " ")
	has := func(s ...string) bool {
		for _, x := range s {
			if strings.Contains(t, x) {
				return true
			}
		}
		return false
	}
	var kinds []string
	if strings.HasPrefix(strings.ToUpper(filepath.Base(name)), "PATENTS") {
		return []string{"patent grant"}
	}
	if has("mozilla public license version 2.0", "mozilla public license, version 2.0") {
		kinds = append(kinds, "MPL-2.0")
	}
	if has("apache license") && has("version 2.0") {
		kinds = append(kinds, "Apache-2.0")
	}
	if has("redistribution and use in source and binary forms") {
		if has("neither the name", "names of its contributors may", "name of the author may not") {
			kinds = append(kinds, "BSD-3-Clause")
		} else {
			kinds = append(kinds, "BSD-2-Clause")
		}
	}
	if has("permission is hereby granted, free of charge, to any person obtaining a copy") {
		kinds = append(kinds, "MIT")
	}
	if has("permission to use, copy, modify, and/or distribute this software for any purpose",
		"permission to use, copy, modify, and distribute this software for any purpose with or without fee") {
		kinds = append(kinds, "ISC")
	}
	if has("creative commons") {
		kinds = append(kinds, "CC")
	}
	if has("the author disclaims copyright", "dedicated to the public domain", "placed in the public domain") {
		kinds = append(kinds, "public domain")
	}
	return kinds
}

// thirdParty matches a module's combined notice file for the code it bundles (LICENSE-3RD-PARTY.md).
// Such a file can also list parts that are not compiled in, so it is reproduced but not summarised.
var thirdParty = regexp.MustCompile(`(?i)(3rd|third)[-_ ]?party`)

// ownKinds lists the licenses of a module's own license files, without the patent grants.
func ownKinds(lics []licenseText) []string {
	seen := map[string]bool{}
	var kinds []string
	for _, l := range lics {
		if thirdParty.MatchString(l.Name) {
			continue
		}
		for _, k := range l.Kinds {
			if !seen[k] && k != "patent grant" {
				seen[k] = true
				kinds = append(kinds, k)
			}
		}
	}
	return kinds
}

// summary is the License column: the module's own licenses, plus its combined notice files.
func summary(lics []licenseText) string {
	s := strings.Join(ownKinds(lics), ", ")
	for _, l := range lics {
		if thirdParty.MatchString(l.Name) {
			s += " + " + l.Name
		}
	}
	return s
}

func mplModules(mods []*module, lics [][]licenseText) []*module {
	var mpl []*module
	for i, m := range mods {
		for _, k := range ownKinds(lics[i]) {
			if k == "MPL-2.0" {
				mpl = append(mpl, m)
				break
			}
		}
	}
	return mpl
}

func writeTexts(b *strings.Builder, lics []licenseText) {
	for _, l := range lics {
		fence := "```"
		for strings.Contains(l.Text, fence) {
			fence += "`"
		}
		fmt.Fprintf(b, "\n### %s\n\n%stext\n%s\n%s\n", l.Name, fence, l.Text, fence)
	}
}

func (m *module) binaries() string {
	if len(m.platforms) == len(platforms) {
		return "all"
	}
	var ps []string
	for _, p := range platforms {
		if m.platforms[p] {
			ps = append(ps, p)
		}
	}
	return strings.Join(ps, ", ")
}

// upstream is the module's source repository (the pkg.go.dev page when the host is not known).
func upstream(m *module) string {
	if strings.HasPrefix(m.Path, "github.com/") {
		parts := strings.SplitN(m.Path, "/", 4)
		if len(parts) >= 3 {
			return "https://" + strings.Join(parts[:3], "/")
		}
	}
	return "https://pkg.go.dev/" + m.Path + "@" + m.Version
}

// escapePath applies the module proxy's case encoding (an upper-case letter becomes "!" + lower case).
func escapePath(s string) string {
	var b strings.Builder
	for _, r := range s {
		if 'A' <= r && r <= 'Z' {
			b.WriteByte('!')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func goOutput(env []string, args ...string) (string, error) {
	cmd := exec.Command("go", args...)
	cmd.Env = append(os.Environ(), env...)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
	}
	return strings.TrimSpace(string(out)), nil
}

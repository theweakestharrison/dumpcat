#!/usr/bin/env python3
"""Build the interactive demo of dumpcat.cc (site/demo/) from the real web UI.

The demo is web/ as it is, with its API client (assets/js/api.js) replaced by
site-src/demo/api.js: an in-memory mock with sample data (site-src/demo/data.js)
that simulates backups, restores and verification in the browser. Absolute
/assets/ URLs are moved under /demo/.

  python scripts/build-demo.py          # run after changing web/ or site-src/demo/
                                        # (also refreshes site-src/demo/types.json when Go is installed)
Standard library only. See docs/website.vi.md.
"""
import json
import os
import pathlib
import re
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
SRC = ROOT / "site-src" / "demo"
OUT = ROOT / "site" / "demo"
ASSET_URL = re.compile(r"""(?<=["'(=])/assets/""")


def rewrite(text: str) -> str:
    return ASSET_URL.sub("/demo/assets/", text)


def main() -> None:
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    # storage and notification types straight from the Go code, when Go is here
    try:
        out = subprocess.run(["go", "run", "./scripts/demotypes"], cwd=ROOT, capture_output=True, check=True, timeout=600)
        (SRC / "types.json").write_bytes(out.stdout)
    except (OSError, subprocess.SubprocessError):
        print("go not available: using the committed site-src/demo/types.json")
    types = json.loads((SRC / "types.json").read_text(encoding="utf-8"))
    # the sample weekly digest, rendered by the Go email template (TestEmailPreview)
    try:
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(["go", "test", "./internal/notify", "-run", "TestEmailPreview", "-count=1"], cwd=ROOT, capture_output=True, check=True,
                           timeout=600, env={**os.environ, "DUMPCAT_EMAIL_PREVIEW": tmp})
            shutil.copyfile(pathlib.Path(tmp) / "email-digest.html", SRC / "digest.html")
    except (OSError, subprocess.SubprocessError):
        print("go not available: using the committed site-src/demo/digest.html")
    digest = (SRC / "digest.html").read_text(encoding="utf-8")

    if OUT.exists():
        shutil.rmtree(OUT)
    for src in sorted((WEB / "assets").rglob("*")):
        if src.is_dir():
            continue
        dst = OUT / "assets" / src.relative_to(WEB / "assets")
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix in (".js", ".css", ".html", ".svg"):
            dst.write_text(rewrite(src.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
        else:
            shutil.copyfile(src, dst)
    js = OUT / "assets" / "js"
    (js / "api.js").write_text((SRC / "api.js").read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    (js / "demo-data.js").write_text((SRC / "data.js").read_text(encoding="utf-8").replace("__VERSION__", version), encoding="utf-8", newline="\n")
    (js / "demo-types.js").write_text("// generated by scripts/build-demo.py from the Go code\nexport default " + json.dumps(types, ensure_ascii=False, separators=(",", ":")) + ";\n",
                                      encoding="utf-8", newline="\n")
    (js / "demo-digest.js").write_text("// generated by scripts/build-demo.py from internal/notify (sample weekly digest)\nexport default " + json.dumps(digest, ensure_ascii=False) + ";\n",
                                       encoding="utf-8", newline="\n")
    (js / "demo.js").write_text((SRC / "demo.js").read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    (OUT / "assets" / "demo.css").write_text((SRC / "demo.css").read_text(encoding="utf-8"), encoding="utf-8", newline="\n")

    page = rewrite((WEB / "index.html").read_text(encoding="utf-8"))
    page = page.replace("<title>DumpCat: MySQL, MariaDB, PostgreSQL &amp; SQL Server Backup</title>", "<title>DumpCat: preview the web UI</title>\n"
                        '  <meta name="description" content="The web interface DumpCat gives you after you install it on your own server, with sample data: backups, restores, point-in-time recovery, restore drills, agents and WireGuard. Runs in your browser.">')
    # the app keeps search engines out of a self-hosted DumpCat; the preview on dumpcat.cc may be indexed
    page = page.replace('<meta name="robots" content="noindex, nofollow">',
                        '<meta name="robots" content="index, follow">\n  <link rel="canonical" href="https://dumpcat.cc/demo/">')
    page = page.replace("</head>", '  <link rel="stylesheet" href="/demo/assets/demo.css">\n</head>')
    page = page.replace("</body>", '  <script type="module" src="/demo/assets/js/demo.js"></script>\n</body>')
    assert "/demo/assets/js/app.js" in page and "demo.css" in page and "preview the web UI" in page, "web/index.html changed: update build-demo.py"
    (OUT / "index.html").write_text(page, encoding="utf-8", newline="\n")
    files = sum(1 for p in OUT.rglob("*") if p.is_file())
    print(f"site/demo: {files} files, DumpCat {version}")


if __name__ == "__main__":
    main()
